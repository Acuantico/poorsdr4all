def field_label(key: str, lang: str = DEFAULT_LANG, **kwargs: object) -> str:
    """Texto visible de ``key`` en ``lang``; cae a español si falta.

    Vacío si ``key`` está vacía o no existe en ningún idioma. Si el texto
    resuelto lleva plantillas (``{n}``...), se aplican ``kwargs`` con
    ``str.format``.
    """
    if not key:
        return ""
    table = LABELS.get(lang, {})
    text = table.get(key)
    if text is None:
        text = LABELS.get(DEFAULT_LANG, {}).get(key, "")
    if not text:
        return key
    return text.format(**kwargs) if kwargs else text


__all__ = ["DEFAULT_LANG", "LABELS", "field_label"]
